export const MCP_EXTENSION_FILE = 'mcp.ts';

/** Register portable agent servers through Pi's MCP API without interpreting server configuration. */
export function emitMcpExtension(mcpServersJson: string): string {
  return `// generated by cradle from the agent folder's mcp.json — do not edit
import type { ExtensionAPI } from '@earendil-works/pi-coding-agent';

const servers = JSON.parse(${JSON.stringify(mcpServersJson)}) as Record<string, unknown>;

export default function registerMcpServers(pi: ExtensionAPI): void {
  for (const [name, config] of Object.entries(servers)) {
    try {
      pi.registerMcpServer(name, config as never);
    } catch (error) {
      // Pi owns server validation; one invalid registration must not hide the remaining servers.
      console.warn(\`cradle: MCP server "\${name}" was not registered: \${error instanceof Error ? error.message : String(error)}\`);
    }
  }
}
`;
}
